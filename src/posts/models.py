class PostTypes(models.TextChoices):
    PLAINTEXT = "PT", _("Plain Text")
    MARKDOWN = "MD", _("Markdown")
    IMAGE = "IMG", _("Image")
    VIDEO = "VID", _("Video")


# These are for mapping from the web content type to the post type
